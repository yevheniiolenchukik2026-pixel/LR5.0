// Unit-тест до лабораторної роботи № 5.1 (варіант 10)
#include <iostream> // бібліотека вводу та виводу
#include <cmath>    // математична бібліотека (fabs, sin)
#define UNIT_TEST   // вимикаємо main з main.cpp, щоб не було двох main
#include "main.cpp" // підключаємо код програми з функціями f і calc
using namespace std; // використання стандартного простору імен

// порівнює очікуване та отримане значення і виводить результат
bool check(const char* name, double expected, double actual)
{
    bool ok; // результат порівняння (усі змінні оголошені разом на початку)
    ok = fabs(expected - actual) < 0.00001; // значення збігаються з похибкою 0.00001
    cout << (ok ? "[PASSED] " : "[FAILED] ") << name // виводимо статус та назву тесту
         << " expected = " << expected << ", actual = " << actual << endl; // очікуване та отримане
    return ok; // повертаємо результат перевірки
}

int main() // головна функція тесту
{
    int failed = 0; // лічильник тестів, які не пройшли
    // f(0,0,1) = (0+0+1)/(sin^2(0)+1) = 1
    if (!check("f(0,0,1)", 1.0, f(0, 0, 1))) failed++; // перевірка функції f на простих числах
    // f(1,1,2) = 4/(sin^2(1)+4)
    if (!check("f(1,1,2)", 4.0 / (sin(1.0) * sin(1.0) + 4.0), f(1, 1, 2))) failed++; // очікуване значення рахуємо окремо
    // calc(1,1) = (f(1,1,2)+f(1,2,0)) / (1+f(1,1,2)^2)
    if (!check("calc(1,1)", 2.6006991278, calc(1, 1))) failed++; // перевірка всього виразу, еталон пораховано окремо
    cout << (failed == 0 ? "All tests passed" : "Some tests failed") << endl; // підсумок
    return failed; // 0 якщо всі тести пройдено
}
